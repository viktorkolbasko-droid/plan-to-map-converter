    rows = []
    for n, what, boxes, checks, m, kind in PLACES:
        ha = hits(A, checks, boxes, m, kind); hb = hits(B, checks, boxes, m, kind)
        r = dict(n=n, what=what, checks=checks, before=ha, after=hb)
        if boxes and len(boxes) > 1:
            r['boxes'] = len(boxes); r['boxes_before'] = per_box(A, checks, boxes, m); r['boxes_after'] = per_box(B, checks, boxes, m)
        rows.append(r)
