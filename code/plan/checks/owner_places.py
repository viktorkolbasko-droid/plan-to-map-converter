def hits(J, checks, boxes, margin, kind):
    out = {}
    for c in checks:
        r = J['checks'].get(c)
        if not r: continue
        sp = r['spots']
        if kind: sp = [s for s in sp if kind in s.get('kind', '') or kind in s.get('why', '')]
        if boxes is not None:
            sp = [s for s in sp if any(b[0] - margin <= s['at'][0] <= b[2] + margin and b[1] - margin <= s['at'][1] <= b[3] + margin for b in boxes)]
            n = len(sp)
        else:
            n = len(sp) if kind else r['n'] - (r.get('stop_n') is not None and r['n'] - r['stop_n'] or 0)
        if n: out[c] = n
    return out
def per_box(J, checks, boxes, margin):
    """how many of the boxes have a spot of one of the checks"""
    k = 0
    for b in boxes:
        if any(b[0] - margin <= s['at'][0] <= b[2] + margin and b[1] - margin <= s['at'][1] <= b[3] + margin
               for c in checks for s in J['checks'].get(c, {}).get('spots', [])): k += 1
    return k
