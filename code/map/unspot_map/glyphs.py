_NUM = re.compile(r'[A-Za-z]|-?\d*\.?\d+')


def _fmt(v):
    return ('%.3f' % v).rstrip('0').rstrip('.')


def scale_path(d, k=1.0, dx=0.0, dy=0.0):
    """путь в абсолютных M, L, H, V, C, Z: x' = k x + dx, y' = k y + dy; другая команда — ValueError (громко)"""
    res, cmd, n = [], None, 0
    for t in _NUM.findall(d):
        if t.isalpha():
            if t not in 'MLHVCZ':
                raise ValueError('scale_path: команда %r не поддержана (только M, L, H, V, C, Z)' % t)
            cmd = t; n = 0; res.append(t); continue
        v = float(t)
        if cmd == 'H': r = k * v + dx
        elif cmd == 'V': r = k * v + dy
        else: r = k * v + (dx if n % 2 == 0 else dy)
        n += 1; res.append(_fmt(r))
    s = ''
    for j, x in enumerate(res):
        s += x if x.isalpha() or j == 0 or res[j - 1].isalpha() else ' ' + x
    return s


def glyph_svg(key, cx=15.0, cy=15.0, d=30.0):
    """глиф ключа: центр бейджа в (cx; cy), диаметр d (d = 30 — родной размер; иначе масштаб целиком)"""
    k, dx, dy = d / 30.0, cx - d / 2.0, cy - d / 2.0
    return re.sub(r' d="([^"]+)"', lambda m: ' d="%s"' % scale_path(m.group(1), k, dx, dy), BADGES[key])


def badge_svg(key, cx=15.0, cy=15.0, d=30.0):
    """готовый бейдж: <g data-badge data-figma> + кружок #E1E7EB r = d / 2 + глиф #62677A; для вставки в слой icons"""
    return ('<g data-badge="%s" data-figma="%s"><circle cx="%s" cy="%s" r="%s" fill="%s"/>%s</g>'
            % (key, FIGMA.get(key, ''), _fmt(cx), _fmt(cy), _fmt(d / 2.0), BADGE_FILL, glyph_svg(key, cx, cy, d)))
